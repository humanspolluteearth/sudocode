"""CPython oracle for Python golden tests (docs/TEST-PLAN.md section 3: Python expected output comes from CPython).

For each program `X.py` with a sibling `X.expected.json`, runs the program under the interpreter running this
script, with the expected file's `inputs` piped to stdin and `random.seed(seed)` applied first when `seed` is set.
It records stdout and, if the program raised, the exception as `E-PY-<Name>` at CPython's line and column
(1-based, from the traceback position of the innermost frame in the program file).

  python3.12 scripts/python-oracle.py --check FILES...   # compare with the expected files; exit 1 on any difference
  python3.12 scripts/python-oracle.py --write FILES...   # fill in `expect` (stdout, errors) and `notes`

Only CPython 3.12 is an oracle (PY-01). Both modes refuse other versions unless `--allow-version` is given; then
`--write` says so in `notes` and `--check` prints a warning, so a non-3.12 check can't be mistaken for confirmation.

Programs run with PYTHONHASHSEED=0 (so set and dict-of-set output is repeatable) and stdout is read as raw bytes
(a printed "\r" stays "\r").
"""

import json
import os
import platform
import subprocess
import sys
from pathlib import Path

RUNNER = r"""
import json, random, runpy, sys, traceback
path, seed = sys.argv[1], sys.argv[2]
if seed:
    random.seed(int(seed))
try:
    runpy.run_path(path, run_name="__main__")
except SystemExit:
    raise
except BaseException as exc:
    if isinstance(exc, SyntaxError) and exc.filename == path:
        line, col = exc.lineno, exc.offset
    else:
        frames = [f for f in traceback.extract_tb(exc.__traceback__) if f.filename == path]
        last = frames[-1]
        if last.colno is None:
            raise RuntimeError("CPython gave no column for this error")
        line, col = last.lineno, last.colno + 1
    sys.stdout.flush()
    sys.stderr.write("\n@@ORACLE@@" + json.dumps({"code": "E-PY-" + type(exc).__name__, "line": line, "column": col}))
    sys.exit(1)
"""

MARKER = "@@ORACLE@@"


def run(program: Path, inputs: list[str], seed: int | None) -> dict:
    stdin = "".join(line + "\n" for line in inputs).encode("utf-8")
    # -s: no user site-packages; -P: don't put the script's folder on sys.path. Not -I/-E, which would drop
    # PYTHONHASHSEED.
    proc = subprocess.run(
        [sys.executable, "-s", "-P", "-c", RUNNER, str(program), "" if seed is None else str(seed)],
        input=stdin,
        capture_output=True,
        env={"PYTHONHASHSEED": "0", "PYTHONIOENCODING": "utf-8", "PATH": os.environ.get("PATH", "")},
        timeout=60,
    )
    stdout, stderr = proc.stdout.decode("utf-8"), proc.stderr.decode("utf-8")
    errors = []
    if MARKER in stderr:
        errors.append(json.loads(stderr.split(MARKER, 1)[1]))
    elif proc.returncode != 0:
        raise RuntimeError(f"{program}: oracle failed\n{stderr}")
    return {"stdout": stdout, "errors": errors}


def main(argv: list[str]) -> int:
    mode = "--check" if "--check" in argv else "--write" if "--write" in argv else None
    allow = "--allow-version" in argv
    files = [Path(a) for a in argv if not a.startswith("--")]
    if mode is None or not files:
        print(__doc__)
        return 2
    version = platform.python_version()
    is_312 = sys.version_info[:2] == (3, 12) and platform.python_implementation() == "CPython"
    if not is_312:
        if not allow:
            print(f"Refusing: this is {platform.python_implementation()} {version}, not CPython 3.12.")
            return 2
        print(f"WARNING: {platform.python_implementation()} {version} is not the oracle (CPython 3.12).")
    differences = 0
    for program in files:
        expected_path = program.with_suffix(".expected.json")
        data = json.loads(expected_path.read_text(encoding="utf-8"))
        result = run(program, data.get("inputs", []), data.get("seed"))
        if mode == "--check":
            exp = data["expect"]
            same = exp["stdout"] == result["stdout"] and exp["errors"] == result["errors"]
            print(f"{'same' if same else 'DIFFERENT'}  {program}")
            if not same:
                differences += 1
                print(f"  expected: {json.dumps({'stdout': exp['stdout'], 'errors': exp['errors']})}")
                print(f"  CPython:  {json.dumps(result)}")
        else:
            data["expect"]["stdout"] = result["stdout"]
            data["expect"]["errors"] = result["errors"]
            data["notes"] = f"stdout and errors generated by CPython {version} with scripts/python-oracle.py."
            expected_path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            print(f"wrote {expected_path}")
    print(f"CPython {version}: {differences} difference(s)" if mode == "--check" else f"CPython {version}: done")
    return 1 if differences else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
