import datetime
from datetime import date, timedelta
from datetime import datetime as dt

d = date(2024, 3, 15)
print(d, d.year, d.month, d.day, d.weekday(), d.isoformat())
print(repr(d))
print(d + timedelta(days=20), d - timedelta(days=15), d + timedelta(weeks=2))
print(date(2024, 12, 25) - d, (date(2024, 12, 25) - d).days)
print(date(2024, 3, 1) - date(2024, 2, 1), date(2023, 3, 1) - date(2023, 2, 1))
print(d < date(2024, 4, 1), d == date(2024, 3, 15), d > date(2025, 1, 1))
t = dt(2024, 3, 15, 14, 5, 9)
print(t, t.hour, t.minute, t.second, t.date(), t.year)
print(repr(t))
print(t + timedelta(hours=10), t - timedelta(minutes=10), t + timedelta(days=1, seconds=3600))
print(dt(2024, 3, 15) - dt(2024, 3, 14, 12, 30))
print(dt(2024, 1, 1, 0, 0, 0), dt(2024, 1, 1, 9, 30))
print(t.strftime("%d/%m/%Y"), t.strftime("%H:%M:%S"), t.strftime("%Y-%m-%d %H:%M"))
print(t.strftime("%A %d %B %Y"), t.strftime("%a %b %y"), t.strftime("%I:%M %p"), t.strftime("100%%"))
print(d.strftime("%j %U"), date(2024, 1, 5).strftime("%A"))
print(d.strftime("%d.%m.%y"))
td = timedelta(days=1, hours=2, minutes=3, seconds=4)
print(td, td.days, td.seconds, td.total_seconds(), repr(td))
print(timedelta(days=2) * 3, timedelta(hours=5) + timedelta(hours=20), timedelta(0), timedelta(seconds=-1))
print(timedelta(days=1) > timedelta(hours=23), timedelta(days=1) == timedelta(hours=24))
print(datetime.date(2000, 2, 29), datetime.timedelta(days=366), datetime.datetime(2000, 1, 1).weekday())
print(date(2024, 2, 28) + timedelta(days=2), date(2023, 2, 28) + timedelta(days=2))
age_days = (date(2024, 3, 15) - date(2010, 6, 20)).days
print(age_days, age_days // 365)
print(dt(2024, 3, 15, 8, 0) < dt(2024, 3, 15, 9, 0), date.fromisoformat("2024-03-15") == d)
today = date.today()
now = dt.now()
print(today.year >= 2024, isinstance(today, date), now.year >= 2024, isinstance(now, dt), now.date() >= today)
print(type(today - today).__name__, today - today, (now - now).total_seconds())
