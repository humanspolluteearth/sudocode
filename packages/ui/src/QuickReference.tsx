// The Quick reference panel, as in the design: a Find box, then sections of small titled code samples. Each sample
// has an Insert button that types it at the editor's cursor, except the operator tables the design marks noInsert.
import { useState } from "react";
import { guideUrl, type GuideId } from "./GuidePage.tsx";
import snippets from "./snippets.json" with { type: "json" };

export interface Snippet {
  title: string;
  code: string;
  note: string;
  noInsert?: boolean;
}
export interface SnippetSection {
  section: string;
  items: Snippet[];
}
/** The design's snippets for each language (generated by scripts/gen-snippets.mjs). */
export const SNIPPETS: Record<GuideId, readonly SnippetSection[]> = snippets;

// The design's wording for the link under the snippets, and for the Find box's placeholder.
const FULL_GUIDE: Record<GuideId, string> = {
  edexcel: "Full Edexcel guide and error reference",
  cie: "Full Cambridge guide and built-in functions",
  python: "Full Python guide and error reference",
};
const FIND_HINT: Record<GuideId, string> = {
  edexcel: "FOR, array, RETURN...",
  cie: "CASE, ARRAY, MID...",
  python: "for, list, def...",
};

/** The sections that match the query: a sample matches when its section, title, code or note contains it. */
export function filterSnippets(sections: readonly SnippetSection[], query: string): SnippetSection[] {
  const q = query.trim().toLowerCase();
  return sections
    .map((g) => ({
      section: g.section,
      items: g.items.filter(
        (it) => q === "" || `${g.section} ${it.title} ${it.code} ${it.note}`.toLowerCase().includes(q),
      ),
    }))
    .filter((g) => g.items.length > 0);
}

export interface QuickReferenceProps {
  language: GuideId;
  /** Type a sample at the editor's cursor. */
  onInsert: (code: string) => void;
  onOpenGuide?: ((guide: GuideId) => void) | undefined;
}

export function QuickReference({ language, onInsert, onOpenGuide }: QuickReferenceProps) {
  const [query, setQuery] = useState("");
  const shown = filterSnippets(SNIPPETS[language], query);
  return (
    <section aria-label="Quick reference" className="sc-reference">
      <div className="sc-ref-find">
        <label htmlFor="sc-ref-q">Find</label>
        <input
          id="sc-ref-q"
          type="search"
          value={query}
          placeholder={FIND_HINT[language]}
          onChange={(e) => {
            setQuery(e.target.value);
          }}
        />
      </div>
      {shown.length === 0 && <div className="sc-ref-empty">No matches.</div>}
      {shown.map((g) => (
        <div key={g.section}>
          <h3 className="sc-ref-section-title">{g.section}</h3>
          {g.items.map((it) => (
            <article key={it.title} className="sc-ref-item">
              <div className="sc-ref-head">
                <span className="sc-ref-title">{it.title}</span>
                {it.noInsert !== true && (
                  <button
                    type="button"
                    className="sc-ref-insert"
                    aria-label={`Insert ${it.title} at the cursor`}
                    onClick={() => {
                      onInsert(it.code);
                    }}
                  >
                    Insert
                  </button>
                )}
              </div>
              <pre tabIndex={0} aria-label={`${it.title} example`}>
                {it.code}
              </pre>
              {it.note !== "" && <div className="sc-ref-note">{it.note}</div>}
            </article>
          ))}
        </div>
      ))}
      <div className="sc-ref-full">
        <a
          href={guideUrl(language)}
          onClick={(e) => {
            if (e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey) return;
            e.preventDefault();
            onOpenGuide?.(language);
          }}
        >
          {FULL_GUIDE[language]}
        </a>
      </div>
    </section>
  );
}
